#!/usr/bin/env python3
"""Generate and verify the same versioned industry contract for backend and browser clients.

Industry definitions are data, not database seed records. No customer data is created.
"""
from pathlib import Path
import json, sys
ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'scripts/industry-catalogue.v1.json'
MANIFESTS = [ROOT / 'backend/src/catalog/industry-manifest.json',
             ROOT / 'lexa-frontend/src/domain/catalog/industry-manifest.json']
GENERATED = ROOT / 'backend/src/catalog/industry-contract.generated.ts'


def render():
    data = json.loads(SOURCE.read_text(encoding='utf-8'))
    industries = data['industries']
    presets = data['presets']
    allowed = {i['code'] for i in industries}
    keys = [p['key'] for p in presets]
    assert len(industries) == 13 and len(set(allowed)) == 13
    assert len(keys) == len(set(keys)) and 'general' in keys
    assert not allowed.intersection(data['retiredIndustryCodes'])
    for p in presets:
        assert set(p['industries']) <= allowed, p['key']
        fields = {f['key'] for f in p['fields']}
        assert len(fields) == len(p['fields'])
        assert set(p['variants']) <= fields, p['key']
        assert p['stock'] in ('serial','batch','quantity','none')
    for i in industries:
        assert len(i['categoryPaths']) > 0
        assert all(1 <= len(path) <= 8 and all(len(node) <= 100 for node in path) for path in i['categoryPaths'])
    text = SOURCE.read_text(encoding='utf-8')
    rules = (ROOT / 'backend/src/business-setup/business-setup.rules.ts').read_text(encoding='utf-8')
    expected_codes = 'export const availableIndustryCodes = '+json.dumps([i['code'] for i in industries])+' as const;'
    expected_retired = 'export const retiredIndustryCodes = '+json.dumps(data['retiredIndustryCodes'])+' as const;'
    assert expected_codes in rules and expected_retired in rules, 'Business setup code list is out of sync with industry manifest'
    ts = '// GENERATED by scripts/sync_industry_catalogue.py. Do not edit by hand.\n'
    ts += 'export const INDUSTRY_CODES = '+json.dumps([i['code'] for i in industries])+' as const;\n'
    ts += 'export const RETIRED_INDUSTRY_CODES = '+json.dumps(data['retiredIndustryCodes'])+' as const;\n'
    ts += 'export const INDUSTRY_CATEGORIES = '+json.dumps({i['code']:i['categoryPaths'] for i in industries},separators=(',',':'),ensure_ascii=False)+' as const;\n'
    ts += 'export const INDUSTRY_LABELS = '+json.dumps({i['code']:i['label'] for i in industries},separators=(',',':'),ensure_ascii=False)+' as const;\n'
    ts += 'export const INDUSTRY_POLICIES = '+json.dumps({p['key']:{'industries':p['industries'],'stock':p['stock'],'fields':p['fields'],'variants':p['variants'],'identifiers':p['identifiers']} for p in presets},separators=(',',':'),ensure_ascii=False)+' as const;\n'
    ts += 'export const LEGACY_PRODUCT_TYPE_FIELDS = '+json.dumps(data['legacyReadOnlyProductTypes'])+' as const;\n'
    return text,ts


def main():
    text,ts=render()
    expected={**{p:text for p in MANIFESTS}, GENERATED:ts}
    if '--check' in sys.argv:
        diffs=[str(p.relative_to(ROOT)) for p,v in expected.items() if not p.is_file() or p.read_text(encoding='utf-8') != v]
        if diffs: raise SystemExit('Industry catalogue drift: '+', '.join(diffs)+'; regenerate with python3 scripts/sync_industry_catalogue.py')
        print('13-industry catalogue contract synchronized for backend, frontend, and all API clients.')
    else:
        for p,v in expected.items():
            p.parent.mkdir(parents=True,exist_ok=True)
            p.write_text(v,encoding='utf-8')
        print('Generated 13-industry backend and frontend manifests.')

if __name__ == '__main__':main()
