#!/usr/bin/env python3
"""Compile the approved tenant niche catalogue for the API and web clients.

Specialties govern product suggestions, not product permission or stock ownership.
"""
from __future__ import annotations
import hashlib, json, re, sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'scripts/business-specialties.v1.json'
CATALOG=ROOT/'scripts/industry-catalogue.v1.json'
TARGETS=[ROOT/'backend/src/catalog/business-specialties.generated.ts',ROOT/'lexa-frontend/src/domain/catalog/business-specialties.generated.ts']

def render() -> str:
    data=json.loads(SOURCE.read_text(encoding='utf-8'))
    catalog=json.loads(CATALOG.read_text(encoding='utf-8'))
    assert data['schemaVersion']==1
    industries={i['code'] for i in catalog['industries']}
    allowed={i: set() for i in industries}
    for p in catalog['presets']:
        for industry in p['industries']:allowed[industry].add(p['key'])
    observed=set()
    for speciality in data['specialties']:
        code=speciality['code'];ind=speciality['industryCode'];types=speciality['recommendedProductTypes']
        assert isinstance(code,str) and re.fullmatch(r'[a-z][a-z0-9_]*\.[a-z][a-z0-9_]*',code),code
        assert code not in observed,code
        observed.add(code)
        assert ind in industries and code.split('.')[0] in {'fashion','beauty','retail','wholesale','hospitality','bakery','hardware','home','repair','education','mobile','electronics','other'}
        assert all(k in allowed[ind] for k in types),code
        assert types and len(types)==len(set(types)),code
        assert isinstance(speciality['label'],str) and len(speciality['label'])<=80
        assert re.fullmatch(r'pack\.[a-z]+\.v[0-9]+',speciality['packCode'])
    digest=hashlib.sha256(SOURCE.read_bytes()).hexdigest()
    literal=json.dumps(data['specialties'],separators=(',',':'),ensure_ascii=False)
    return '''// GENERATED by scripts/sync_business_specialties.py. Do not edit by hand.
/** Business specialties are recommendations, never new tenant permissions. */
export const BUSINESS_SPECIALTY_SCHEMA_VERSION = 1 as const;
export const BUSINESS_SPECIALTY_POLICY_HASH = "'''+digest+'''" as const;
export const BUSINESS_SPECIALTIES = '''+literal+''' as const;
export type BusinessSpecialty = {readonly code:string;readonly industryCode:string;readonly label:string;readonly packCode:string;readonly recommendedProductTypes:readonly string[]};
const specialties:readonly BusinessSpecialty[]=BUSINESS_SPECIALTIES;
export function availableBusinessSpecialties(industries:readonly string[]):BusinessSpecialty[]{
 const selected=new Set(industries);
 return specialties.filter(item=>selected.has(item.industryCode));
}
/** Reject stale, forged and cross-industry selections; no implicit grant by niche. */
export function validateBusinessSpecialties(raw:unknown, industries:readonly string[]):string[]{
 if(raw===undefined||raw===null)return [];
 if(!Array.isArray(raw)||raw.length>specialties.length||raw.some(v=>typeof v!=="string"))throw new Error("Choose valid business specialties.");
 const permitted=new Set(availableBusinessSpecialties(industries).map(item=>item.code));
 if(raw.some(code=>!permitted.has(code as string)))throw new Error("A selected specialty does not belong to your active business activities.");
 return [...new Set(raw as string[])].sort();
}
/** Only sorts approved product suggestions. The industry itself still authorizes creation. */
export function recommendedBusinessProducts(industries:readonly string[], chosen:readonly string[]):string[]{
 const approved=new Set(availableBusinessSpecialties(industries).map(item=>item.code));
 const types=new Set<string>();
 for(const item of specialties){if(approved.has(item.code)&&chosen.includes(item.code))for(const key of item.recommendedProductTypes)types.add(key);}
 return [...types];
}
'''

def main():
    ts=render()
    if '--check' in sys.argv:
        diff=[str(p.relative_to(ROOT)) for p in TARGETS if not p.exists() or p.read_text(encoding='utf-8')!=ts]
        if diff:raise SystemExit('Business specialty contract drift: '+', '.join(diff))
        print('Business specialties synchronized across API and web clients.')
    else:
        for t in TARGETS:t.write_text(ts,encoding='utf-8')
        print('Generated business specialties for API and web clients.')
if __name__=='__main__':main()
