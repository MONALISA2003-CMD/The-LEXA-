CREATE TABLE "module_record_links" (
  "id" UUID NOT NULL,
  "tenant_id" UUID NOT NULL,
  "branch_id" UUID NOT NULL,
  "source_module_id" TEXT NOT NULL,
  "source_record_id" TEXT NOT NULL,
  "target_module_id" TEXT NOT NULL,
  "target_record_id" TEXT NOT NULL,
  "relation_type" TEXT NOT NULL DEFAULT 'workflow_handoff',
  "created_by_user_id" UUID,
  "created_at" TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT "module_record_links_pkey" PRIMARY KEY ("id"),
  CONSTRAINT "module_record_links_tenant_fkey" FOREIGN KEY ("tenant_id") REFERENCES "tenants"("id") ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT "module_record_links_branch_fkey" FOREIGN KEY ("branch_id") REFERENCES "branches"("id") ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT "module_record_links_source_fkey" FOREIGN KEY ("tenant_id", "branch_id", "source_module_id", "source_record_id") REFERENCES "module_records"("tenant_id", "branch_id", "module_id", "record_id") ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT "module_record_links_target_fkey" FOREIGN KEY ("tenant_id", "branch_id", "target_module_id", "target_record_id") REFERENCES "module_records"("tenant_id", "branch_id", "module_id", "record_id") ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT "module_record_links_creator_fkey" FOREIGN KEY ("created_by_user_id") REFERENCES "users"("id") ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT "module_record_links_not_self" CHECK (NOT ("source_module_id" = "target_module_id" AND "source_record_id" = "target_record_id"))
);
CREATE UNIQUE INDEX "module_record_links_unique_edge" ON "module_record_links"("tenant_id", "branch_id", "source_module_id", "source_record_id", "target_module_id", "target_record_id", "relation_type");
CREATE INDEX "module_record_links_source_idx" ON "module_record_links"("tenant_id", "branch_id", "source_module_id", "source_record_id", "created_at" DESC);
CREATE INDEX "module_record_links_target_idx" ON "module_record_links"("tenant_id", "branch_id", "target_module_id", "target_record_id", "created_at" DESC);

CREATE TABLE "module_domain_events" (
  "id" UUID NOT NULL,
  "tenant_id" UUID NOT NULL,
  "branch_id" UUID NOT NULL,
  "module_id" TEXT NOT NULL,
  "record_id" TEXT,
  "event_type" TEXT NOT NULL,
  "payload" JSONB NOT NULL DEFAULT '{}'::jsonb,
  "dedupe_key" TEXT,
  "outbox_status" TEXT NOT NULL DEFAULT 'pending',
  "attempts" INTEGER NOT NULL DEFAULT 0,
  "last_error" TEXT,
  "actor_user_id" UUID,
  "created_at" TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "processed_at" TIMESTAMPTZ(3),
  CONSTRAINT "module_domain_events_pkey" PRIMARY KEY ("id"),
  CONSTRAINT "module_domain_events_tenant_fkey" FOREIGN KEY ("tenant_id") REFERENCES "tenants"("id") ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT "module_domain_events_branch_fkey" FOREIGN KEY ("branch_id") REFERENCES "branches"("id") ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT "module_domain_events_module_fkey" FOREIGN KEY ("module_id") REFERENCES "module_definitions"("module_id") ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT "module_domain_events_actor_fkey" FOREIGN KEY ("actor_user_id") REFERENCES "users"("id") ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT "module_domain_events_status_check" CHECK ("outbox_status" IN ('pending', 'processing', 'processed', 'failed'))
);
CREATE UNIQUE INDEX "module_domain_events_dedupe_key" ON "module_domain_events"("tenant_id", "dedupe_key");
CREATE INDEX "module_domain_events_workspace_stream_idx" ON "module_domain_events"("tenant_id", "branch_id", "created_at" DESC);
CREATE INDEX "module_domain_events_record_stream_idx" ON "module_domain_events"("tenant_id", "branch_id", "module_id", "record_id", "created_at" DESC);
CREATE INDEX "module_domain_events_outbox_idx" ON "module_domain_events"("outbox_status", "created_at") WHERE "outbox_status" = 'pending';
