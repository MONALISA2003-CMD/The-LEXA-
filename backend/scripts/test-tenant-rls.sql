-- DISPOSABLE-CI-ONLY RLS test. Never run this script against production.
-- It forces tenant isolation policies on every public base table with a UUID tenant_id,
-- then verifies cross-tenant read and write isolation using a NOLOGIN, NOBYPASSRLS role.
BEGIN;

DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'lexa_rls_ci') THEN
    EXECUTE 'DROP OWNED BY lexa_rls_ci';
    EXECUTE 'DROP ROLE lexa_rls_ci';
  END IF;
  EXECUTE 'CREATE ROLE lexa_rls_ci NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS';
END $$;

GRANT USAGE ON SCHEMA public TO lexa_rls_ci;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO lexa_rls_ci;
GRANT USAGE, SELECT, UPDATE ON ALL SEQUENCES IN SCHEMA public TO lexa_rls_ci;

DO $$
DECLARE item RECORD;
BEGIN
  FOR item IN
    SELECT c.table_schema, c.table_name
    FROM information_schema.columns c
    JOIN information_schema.tables t
      ON t.table_schema = c.table_schema AND t.table_name = c.table_name
    WHERE c.table_schema = 'public'
      AND c.column_name = 'tenant_id'
      AND c.data_type = 'uuid'
      AND t.table_type = 'BASE TABLE'
  LOOP
    EXECUTE format('ALTER TABLE %I.%I ENABLE ROW LEVEL SECURITY', item.table_schema, item.table_name);
    EXECUTE format('ALTER TABLE %I.%I FORCE ROW LEVEL SECURITY', item.table_schema, item.table_name);
    EXECUTE format('DROP POLICY IF EXISTS lexa_tenant_isolation ON %I.%I', item.table_schema, item.table_name);
    EXECUTE format(
      'CREATE POLICY lexa_tenant_isolation ON %I.%I USING (tenant_id = NULLIF(current_setting(''lexa.tenant_id'', true), '''')::uuid) WITH CHECK (tenant_id = NULLIF(current_setting(''lexa.tenant_id'', true), '''')::uuid)',
      item.table_schema, item.table_name
    );
  END LOOP;
END $$;

CREATE TABLE IF NOT EXISTS public.lexa_rls_probe (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id uuid NOT NULL,
  payload text NOT NULL
);
-- Seed while the table is not yet FORCE-RLS protected. The whole test is rolled back.
TRUNCATE public.lexa_rls_probe RESTART IDENTITY;
INSERT INTO public.lexa_rls_probe (tenant_id, payload) VALUES
  ('11111111-1111-4111-8111-111111111111', 'tenant-a'),
  ('22222222-2222-4222-8222-222222222222', 'tenant-b');
ALTER TABLE public.lexa_rls_probe ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.lexa_rls_probe FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS lexa_tenant_isolation ON public.lexa_rls_probe;
CREATE POLICY lexa_tenant_isolation ON public.lexa_rls_probe
  USING (tenant_id = NULLIF(current_setting('lexa.tenant_id', true), '')::uuid)
  WITH CHECK (tenant_id = NULLIF(current_setting('lexa.tenant_id', true), '')::uuid);
GRANT SELECT, INSERT, UPDATE, DELETE ON public.lexa_rls_probe TO lexa_rls_ci;
GRANT USAGE, SELECT, UPDATE ON SEQUENCE public.lexa_rls_probe_id_seq TO lexa_rls_ci;

SET LOCAL ROLE lexa_rls_ci;
SELECT set_config('lexa.tenant_id', '11111111-1111-4111-8111-111111111111', true);
DO $$
DECLARE visible_count integer;
BEGIN
  SELECT count(*) INTO visible_count FROM public.lexa_rls_probe;
  IF visible_count <> 1 THEN RAISE EXCEPTION 'Tenant RLS read isolation failed: expected 1 row, got %', visible_count; END IF;
  BEGIN
    INSERT INTO public.lexa_rls_probe (tenant_id, payload)
      VALUES ('22222222-2222-4222-8222-222222222222', 'cross-tenant-write');
    RAISE EXCEPTION 'Tenant RLS write isolation failed: cross-tenant insert unexpectedly succeeded';
  EXCEPTION WHEN insufficient_privilege THEN
    NULL;
  END;
END $$;

RESET ROLE;
ROLLBACK;
